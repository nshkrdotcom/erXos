# frozen_string_literal: true

require_relative 'abi_model'
require_relative 'abi_profile'

module Erx
  module ABI
    # Emits, for each frame protocol with "reader c", the table liberx's
    # erx_profile.c interprets and the typed functions over it
    # (docs/design-abi.md, "Program protocol"): include/erx/P_profile.h with
    # a struct for each tuple, map and union, an iterator type of its own for
    # each list, and liberx/generated/P_profile.c with the table, whose
    # offsets are the compiler's own offsetof, and static asserts that the C
    # check's fixed bounds hold it. A kind's index in the table is its index in
    # the protocol's declarations, then the built-in kinds it uses. For each
    # union a frame carries whose cases hold capabilities, it also emits
    # P_UNION_CAPS, the most one case holds, and P_UNION_caps, the walk that
    # names a value's capabilities, so a case the protocol gains is walked
    # without a hand-written switch to forget it.
    class ProfileEmitter
      INTEGER_TYPES = { 'u8' => 'uint8_t', 'u16' => 'uint16_t', 'u32' => 'uint32_t', 'u64' => 'uint64_t' }.freeze
      # An offset's C type, FreeBSD's off_t (Protocols.offset_kind).
      OFFSET_TYPE = 'int64_t'
      # A time's C type, FreeBSD's time_t in a struct of its own (Protocols.time_kind).
      TIME_TYPE = 'erx_profile_time_t'
      BASE_MAX = { 'u8' => 0xff, 'u16' => 0xffff, 'u32' => 0xffff_ffff, 'u64' => 0xffff_ffff_ffff_ffff }.freeze

      def self.outputs(schema)
        schema.protocols.select { |protocol| protocol[:reader] == 'c' }.each_with_object({}) do |protocol, files|
          emitter = new(protocol)
          files["include/erx/#{emitter.short}_profile.h"] = emitter.header
          files["liberx/generated/#{emitter.short}_profile.c"] = emitter.source
        end.freeze
      end

      def initialize(protocol)
        @protocol = protocol
        @kinds = protocol.fetch(:kinds)
        @frames = protocol.fetch(:frames)
        @named = protocol.fetch(:named)
        builtins = [*Protocols::FRAME_BUILTINS, *INTEGER_TYPES.keys].select { |name| referenced.include?(name) }
        builtins << 'slot' if protocol.fetch(:frames).any? { |frame| frame.fetch(:slot) }
        @order = @kinds.keys + builtins
        @names = @order + protocol.fetch(:totals).keys + protocol.fetch(:frames).map { |frame| frame.fetch(:name) }
      end

      def short = @protocol.fetch(:name).delete_prefix('erx_')

      def header
        guard = "ERX_#{short.upcase}_PROFILE_H"
        [banner,
         '', "#ifndef #{guard}", "#define #{guard}", '',
         "/* The #{@protocol.fetch(:name)} frame profile's C check (docs/design-abi.md#program-protocol). */",
         '', *abi_include, '#include <erx/profile.h>', '', frame_enum, named_enum, enums, types, frame_types, prototypes, cap_prototypes, '',
         "#endif /* !#{guard} */", ''].join("\n")
      end

      def source
        [banner,
         '', '#include <stddef.h>', '#include <stdint.h>', '', "#include <erx/#{short}_profile.h>", '',
         "#define\tNELEM(a)\t(sizeof(a) / sizeof((a)[0]))\n", values_tables, fields_tables, cases_tables, kinds_table, names_table, rules_tables, named_tables,
         frames_table, profile, bounds, functions, to_program_function, cap_functions].join("\n")
      end

      private

      # Every generated file's head: its license, which a program's build receipt resolves
      # (Erx::PackProvenance), and where it comes from.
      def banner
        ['/*', ' * Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>', ' * SPDX-License-Identifier: BSD-2-Clause',
         " * Generated by tools/lib/erx/abi_emit_profile.rb from #{@protocol.fetch(:source)}. Do not edit.",
         ' */'].join("\n")
      end

      def prefix = "erx_#{short}"

      def referenced
        @referenced ||= @kinds.values.flat_map { |kind| Protocols::Profile.inner_kinds(kind) } +
                        @frames.flat_map { |frame| Protocols::Profile.frame_kinds(frame) }
      end

      def index(name) = @order.index(name) || raise(SchemaError, "no kind #{name}")

      def atoms_only?(kind) = kind.fetch(:cases).all? { |item| item.fetch(:fields).empty? }

      def reply?(frame) = frame.key?(:replies)

      # The frames to the program the channel carries after its startup
      # message, those tagged with the protocol's own name, which
      # P_check_to_program tells apart by their envelopes.
      def to_program = @frames.select { |frame| frame.fetch(:direction) == 'to' && frame.fetch(:tag) == @protocol.fetch(:name) }

      def frame_constant(frame) = "#{prefix}_frame_#{frame.fetch(:name)}".upcase

      # A protocol with a capability kind names erx_cap_t, which the ABI's
      # own header declares (scalar cap).
      def abi_include
        @kinds.values.any? { |kind| kind[:capability] } ? ['#include <erx/abi.h>'] : []
      end

      # The C type of a value of kind name. A capability is erx_cap_t, the
      # ABI's single-member struct, so a handle neither converts to nor
      # from an integer field without saying so.
      def c_type(name)
        kind = @kinds[name]
        return INTEGER_TYPES.fetch(name) if INTEGER_TYPES.key?(name)
        return 'bool' if name == 'boolean'
        return 'int32_t' if @named.key?(name)
        return 'uint8_t' if name == 'slot'

        case kind.fetch(:form)
        when 'integer'
          if kind[:capability] then 'erx_cap_t'
          elsif kind[:offset] then OFFSET_TYPE
          elsif kind[:time] then TIME_TYPE
          else INTEGER_TYPES.fetch(kind.fetch(:base))
          end
        when 'text' then 'erx_profile_text_t'
        when 'list' then "#{prefix}_#{name}_iter_t"
        when 'union' then atoms_only?(kind) ? 'uint16_t' : "#{prefix}_#{name}_t"
        else "#{prefix}_#{name}_t"
        end
      end

      # Member names for a tuple's or a case's fields: each kind's name, a
      # named number's member name (Protocols::NAMED_NUMBERS), with _1, _2 ...
      # when a kind repeats.
      def member_names(kinds)
        names = kinds.map { |kind| Protocols::NAMED_NUMBERS[kind]&.member || kind }
        names.map.with_index do |name, position|
          names.count(name) > 1 ? "#{name}_#{names.first(position + 1).count(name)}" : name
        end
      end

      def enum_name(union, atoms) = "#{prefix}_#{union}_#{atoms.join('_')}".upcase

      # Each frame's index in the table, the frame argument of erx_profile_check.
      def frame_enum
        constants = @frames.each_with_index.map { |frame, position| "\t#{frame_constant(frame)} = #{position}," }
        "/* The frames, by their index in the table. */\nenum {\n#{constants.join("\n")}\n};\n"
      end

      # Each named number's kind, by its index in the table: the kind argument of
      # erx_profile_named_name, by which a frame's writer finds a number's atom.
      def named_enum
        constants = @order.each_with_index.select { |name, _| Protocols::NAMED_NUMBERS.key?(name) }
                          .map { |name, position| "\t#{prefix.upcase}_KIND_#{name.upcase} = #{position}," }
        return '' if constants.empty?

        "/* The named numbers' kinds, by their index in the table. */\nenum {\n#{constants.join("\n")}\n};\n"
      end

      # A reply frame's struct, the request case it answers and that case's
      # reply, and for the frames to the program after the startup message
      # the struct P_check_to_program fills: which frame, a reply's slot and
      # the frame's value.
      def frame_types
        replies = @frames.select { |frame| reply?(frame) }.map do |frame|
          members = frame.fetch(:replies).map { |request, reply| "\t\t#{c_type(reply)}\t#{request};" }
          "/* A #{frame.fetch(:name)} frame's value: the reply to the #{frame.fetch(:union)} case its slot holds. */\n" \
            "typedef struct #{prefix}_#{frame.fetch(:name)} {\n\tuint16_t\trequest;\t/* the case, #{prefix.upcase}_#{frame.fetch(:union).upcase}_... */\n" \
            "\tunion {\n#{members.join("\n")}\n\t} u;\n} #{prefix}_#{frame.fetch(:name)}_t;\n"
        end
        members = to_program.map { |frame| "\t\t#{frame_type(frame)}\t#{frame.fetch(:name)};" }
        to = "/* A frame to the program after its startup message: which frame, its slot, its value. */\n" \
             "typedef struct #{prefix}_to_program {\n\tuint16_t\tframe;\t/* #{prefix.upcase}_FRAME_... */\n" \
             "\tuint8_t\t\tslot;\t/* a slotted frame's */\n\tunion {\n#{members.join("\n")}\n\t} u;\n} #{prefix}_to_program_t;\n"
        [*replies, *(to_program.empty? ? [] : [to])].join("\n")
      end

      # The C type of a frame's value.
      def frame_type(frame) = reply?(frame) ? "#{prefix}_#{frame.fetch(:name)}_t" : c_type(frame.fetch(:kind))

      def enums
        @kinds.select { |_, kind| kind.fetch(:form) == 'union' && !kind.fetch(:cases).empty? }.map do |name, kind|
          constants = kind.fetch(:cases).each_with_index.map { |item, value| "\t#{enum_name(name, item.fetch(:atoms))} = #{value}," }
          "/* The cases of #{name}, the values of its which. */\nenum {\n#{constants.join("\n")}\n};\n"
        end.join("\n")
      end

      def types
        @kinds.filter_map do |name, kind|
          case kind.fetch(:form)
          when 'list'
            "/* #{name}: at most #{kind.dig(:max, :value)} #{kind.fetch(:element)}#{kind.fetch(:ascending) ? ', ascending' : ''}. */\n" \
              "typedef struct #{prefix}_#{name}_iter {\n\terx_profile_list_t\tview;\n} #{c_type(name)};\n"
          when 'tuple'
            members = member_names(kind.fetch(:elements)).zip(kind.fetch(:elements))
            struct(name, members.map { |member, element| "\t#{c_type(element)}\t#{member};" })
          when 'map'
            members = kind.fetch(:fields).flat_map do |field, field_kind|
              line = "\t#{c_type(field_kind)}\t#{field};"
              kind.fetch(:optional).include?(field) ? ["\tbool\thas_#{field};", line] : [line]
            end
            struct(name, members)
          when 'union'
            next if atoms_only?(kind)

            cases = kind.fetch(:cases).reject { |item| item.fetch(:fields).empty? }.map do |item|
              members = member_names(item.fetch(:fields)).zip(item.fetch(:fields))
              "\t\tstruct {\n#{members.map { |member, field| "\t\t\t#{c_type(field)}\t#{member};" }.join("\n")}\n" \
                "\t\t} #{item.fetch(:c_name)};"
            end
            struct(name, ["\tuint16_t\twhich;", "\tunion {\n#{cases.join("\n")}\n\t} u;"])
          end
        end.join("\n")
      end

      def struct(name, members)
        "typedef struct #{prefix}_#{name} {\n#{members.join("\n")}\n} #{prefix}_#{name}_t;\n"
      end

      # A frame check's parameters after the scratch: a reply frame's busy,
      # the request case each slot holds or ERX_PROFILE_NONE, a slotted
      # frame's slot, and the frame's value.
      def check_parameters(frame)
        [*(reply?(frame) ? ['const uint16_t busy[ERX_PROFILE_SLOTS]'] : []),
         *(frame.fetch(:slot) ? ['uint8_t *slot'] : []), "#{frame_type(frame)} *#{frame.fetch(:name)}"].join(', ')
      end

      def prototypes
        frames = @frames.map do |frame|
          "bool\t#{prefix}_check_#{frame.fetch(:name)}(const uint8_t *frame, size_t len,\n" \
            "\t    void *scratch, size_t scratch_len, #{check_parameters(frame)},\n" \
            "\t    erx_profile_refusal_t *refusal);"
        end
        unless to_program.empty?
          frames << "/* A frame to the program after its startup message, told apart by its envelope. */\n" \
                    "bool\t#{prefix}_check_to_program(const uint8_t *frame, size_t len,\n" \
                    "\t    void *scratch, size_t scratch_len, const uint16_t busy[ERX_PROFILE_SLOTS],\n" \
                    "\t    #{prefix}_to_program_t *to_program, erx_profile_refusal_t *refusal);"
        end
        lists = @kinds.select { |_, kind| kind.fetch(:form) == 'list' }.map do |name, kind|
          "bool\t#{prefix}_#{name}_next(#{c_type(name)} *it, #{c_type(kind.fetch(:element))} *element);"
        end
        ["extern const erx_profile_t #{prefix}_profile;", '',
         "size_t\t#{prefix}_scratch_bytes(size_t len);", *frames, *lists,
         "const char *#{prefix}_kind_name(uint16_t kind);"].join("\n")
      end

      def values_tables
        @kinds.select { |_, kind| kind[:values] }.map do |name, kind|
          "static const uint64_t #{name}_values[] = { #{kind[:values].map { |value| "UINT64_C(#{value.fetch(:value)})" }.join(', ')} };\n"
        end.join
      end

      def field(kind:, offset:, name: nil, has: nil)
        "\t{ .name = #{name ? "\"#{name}\"" : 'NULL'}, .kind = #{index(kind)}, .offset = #{offset}, " \
          ".has_offset = #{has || 'ERX_PROFILE_NONE'} },"
      end

      def fields_tables
        @kinds.filter_map do |name, kind|
          type = "#{prefix}_#{name}_t"
          rows = case kind.fetch(:form)
                 when 'tuple'
                   member_names(kind.fetch(:elements)).zip(kind.fetch(:elements)).map do |member, element|
                     field(kind: element, offset: "offsetof(#{type}, #{member})")
                   end
                 when 'map'
                   kind.fetch(:fields).map do |key, field_kind|
                     has = kind.fetch(:optional).include?(key) ? "offsetof(#{type}, has_#{key})" : nil
                     field(kind: field_kind, offset: "offsetof(#{type}, #{key})", name: key, has: has)
                   end
                 when 'union'
                   kind.fetch(:cases).reject { |item| item.fetch(:fields).empty? }.map do |item|
                     members = member_names(item.fetch(:fields)).zip(item.fetch(:fields))
                     rows = members.map do |member, field_kind|
                       field(kind: field_kind, offset: "offsetof(#{type}, u.#{item.fetch(:c_name)}.#{member}) - " \
                                                       "offsetof(#{type}, u.#{item.fetch(:c_name)})")
                     end
                     "static const erx_profile_field_t #{name}_#{item.fetch(:c_name)}_fields[] = {\n#{rows.join("\n")}\n};\n"
                   end.join("\n")
                 end
          next nil if rows.nil? || rows.empty?

          kind.fetch(:form) == 'union' ? rows : "static const erx_profile_field_t #{name}_fields[] = {\n#{rows.join("\n")}\n};\n"
        end.join("\n")
      end

      def cases_tables
        @kinds.select { |_, kind| kind.fetch(:form) == 'union' && !kind.fetch(:cases).empty? }.map do |name, kind|
          atoms = kind.fetch(:cases).map do |item|
            "static const char *const #{name}_#{item.fetch(:c_name)}_atoms[] = { #{item.fetch(:atoms).map { |atom| "\"#{atom}\"" }.join(', ')} };"
          end
          rows = kind.fetch(:cases).map do |item|
            fields = item.fetch(:fields).empty? ? 'NULL' : "#{name}_#{item.fetch(:c_name)}_fields"
            offset = item.fetch(:fields).empty? || atoms_only?(kind) ? '0' : "offsetof(#{prefix}_#{name}_t, u.#{item.fetch(:c_name)})"
            reply = item.fetch(:reply) ? index(item.fetch(:reply)) : 'ERX_PROFILE_NONE'
            "\t{ .atoms = #{name}_#{item.fetch(:c_name)}_atoms, .fields = #{fields}, .natoms = #{item.fetch(:atoms).size}, " \
              ".nfields = #{item.fetch(:fields).size}, .offset = #{offset}, .reply = #{reply} },"
          end
          "#{atoms.join("\n")}\nstatic const erx_profile_case_t #{name}_cases[] = {\n#{rows.join("\n")}\n};\n"
        end.join("\n")
      end

      def kinds_table
        rows = @order.map { |name| "\t[#{index(name)}] = #{kind_row(name)}," }
        "/* Each kind; refusals name it by its index here. */\nstatic const erx_profile_kind_t kinds[] = {\n#{rows.join("\n")}\n};\n"
      end

      def kind_row(name)
        kind = @kinds[name]
        rule = ->(index) { index.nil? ? 'ERX_PROFILE_NONE' : index }
        common = ".name = \"#{name}\", .size = sizeof(#{c_type(name)}), " \
                 ".sum = #{rule.call(kind && kind[:sum] && @protocol.fetch(:totals).keys.index(kind[:sum]))}, " \
                 ".refers = #{rule.call(@protocol.fetch(:refers).index { |item| item.fetch(:kind) == name })}, " \
                 ".target = #{rule.call(@protocol.fetch(:refers).index { |item| item.fetch(:list) == name })}"
        return "{ #{common}, .form = ERX_PROFILE_BOOLEAN }" if name == 'boolean'
        return "{ #{common}, .form = ERX_PROFILE_NAMED, .table = #{@named.keys.index(name)} }" if @named.key?(name)
        return "{ #{common}, .form = ERX_PROFILE_INTEGER, .min = 0, .max = ERX_PROFILE_SLOTS - 1 }" if name == 'slot'
        return "{ #{common}, .form = ERX_PROFILE_INTEGER, .min = 0, .max = UINT64_C(#{BASE_MAX.fetch(name)}) }" unless kind

        fields = "{\n\t    #{common.gsub(', .', ",\n\t    .")}"
        case kind.fetch(:form)
        when 'integer' then "#{fields},\n\t    #{integer_members(name, kind)} }"
        when 'text' then "#{fields},\n\t    #{text_members(kind)} }"
        when 'tuple'
          "#{fields},\n\t    .form = ERX_PROFILE_TUPLE, .fields = #{name}_fields, .nfields = #{kind.fetch(:elements).size} }"
        when 'map'
          "#{fields},\n\t    .form = ERX_PROFILE_MAP, .fields = #{name}_fields, .nfields = #{kind.fetch(:fields).size} }"
        when 'list'
          "#{fields},\n" \
            "\t    .form = ERX_PROFILE_LIST, .element = #{index(kind.fetch(:element))}, " \
            ".list_max = #{kind.dig(:max, :value)}, .ascending = #{kind.fetch(:ascending)} }"
        when 'union'
          form = atoms_only?(kind) ? 'ERX_PROFILE_ATOMS' : 'ERX_PROFILE_UNION'
          cases = kind.fetch(:cases).empty? ? 'NULL' : "#{name}_cases"
          "#{fields},\n\t    .form = #{form}, .cases = #{cases}, .ncases = #{kind.fetch(:cases).size} }"
        end
      end

      def integer_members(name, kind)
        return signed_members(kind) if kind[:signed]

        values = kind[:values]&.map { |item| item.fetch(:value) }
        low = values&.min || kind.dig(:min, :value) || 0
        high = values&.max || kind.dig(:max, :value) || BASE_MAX.fetch(kind.fetch(:base))
        members = [".form = ERX_PROFILE_INTEGER", ".min = UINT64_C(#{low})", ".max = UINT64_C(#{high})"]
        members << ".values = #{name}_values, .nvalues = #{values.size}" if values
        members << ".except = UINT64_C(#{kind.dig(:except, :value)}), .has_except = true" if kind[:except]
        members << '.unique = true' if kind[:unique]
        members.join(",\n\t    ")
      end

      # A signed kind's range, an offset's or a time's: int64_t bounds held in min
      # and max as their two's complement (erx/profile.h); -2^63 has no literal of
      # its own in C.
      def signed_members(kind)
        bound = lambda do |number|
          value = number.fetch(:value)
          value == -(1 << 63) ? '(uint64_t)INT64_MIN' : "(uint64_t)INT64_C(#{value})"
        end
        ['.form = ERX_PROFILE_INTEGER', '.sign = true',
         ".min = #{bound.call(kind.fetch(:min))}", ".max = #{bound.call(kind.fetch(:max))}"].join(",\n\t    ")
      end

      def text_members(kind)
        rules = { utf8: 'ERX_PROFILE_UTF8_RULE', assign: 'ERX_PROFILE_ASSIGN_RULE', path: 'ERX_PROFILE_PATH_RULE' }
                .select { |rule, _| kind.fetch(rule) }.values
        rules.insert(kind.fetch(:utf8) ? 1 : 0, 'ERX_PROFILE_NUL_RULE') if kind.fetch(:refuse).include?('nul')
        members = [".form = ERX_PROFILE_TEXT_FORM", ".text_max = #{kind.dig(:max, :value)}",
                   ".rules = #{rules.empty? ? '0' : rules.join(' | ')}"]
        members.join(",\n\t    ")
      end

      def names_table
        "/* The names a refusal gives: each kind's, then each total's, then each frame's. */\n" \
          "static const char *const names[] = {\n#{@names.map { |name| "\t\"#{name}\"," }.join("\n")}\n};\n"
      end

      def rules_tables
        refers = @protocol.fetch(:refers).map do |item|
          "\t{ .low = #{item.fetch(:low)}, .range = #{item.fetch(:range)}, .kind = #{index(item.fetch(:kind))}, " \
            ".list = #{index(item.fetch(:list))} },"
        end
        totals = @protocol.fetch(:totals).map do |total, max|
          "\t{ .max = #{max.fetch(:value)}, .name = #{@names.index(total)} },"
        end
        (refers.empty? ? '' : "static const erx_profile_refers_t refers[] = {\n#{refers.join("\n")}\n};\n") +
          (totals.empty? ? '' : "static const erx_profile_total_t totals[] = {\n#{totals.join("\n")}\n};\n")
      end

      # Each named number's rows, by the protocol names the model formed, and
      # the tables a named kind's table indexes, in the model's order.
      def named_tables
        return '' if @named.empty?

        rows = @named.map do |word, items|
          "/* Each #{word} a frame may name, by its protocol name, and its number. */\n" \
            "static const erx_profile_named_t #{word}_rows[] = {\n#{items.map { |item, number| "\t{ \"#{item}\", #{number} }," }.join("\n")}\n};\n"
        end
        tables = @named.keys.map { |word| "\t{ .rows = #{word}_rows, .nrows = NELEM(#{word}_rows) }," }
        "#{rows.join("\n")}\nstatic const erx_profile_table_t tables[] = {\n#{tables.join("\n")}\n};\n"
      end

      def frames_table
        rows = @frames.map do |frame|
          kind = reply?(frame) ? 'ERX_PROFILE_NONE' : index(frame.fetch(:kind))
          request = reply?(frame) ? frame_constant(@frames.find { |item| item.fetch(:name) == frame.fetch(:request) }) : 'ERX_PROFILE_NONE'
          "\t[#{frame_constant(frame)}] = { .tag = \"#{frame.fetch(:tag)}\", .name = #{@names.index(frame.fetch(:name))}, " \
            ".kind = #{kind}, .request = #{request}, .slot = #{frame.fetch(:slot)} },"
        end
        "static const erx_profile_frame_t frames[] = {\n#{rows.join("\n")}\n};\n"
      end

      def profile
        unique = @protocol.fetch(:unique) ? index(@protocol.fetch(:unique)) : 'ERX_PROFILE_NONE'
        count = ->(table, items) { items.empty? ? ['NULL', 0] : [table, items.size] }
        refers, nrefers = count.call('refers', @protocol.fetch(:refers))
        totals, ntotals = count.call('totals', @protocol.fetch(:totals).to_a)
        tables, ntables = count.call('tables', @named.to_a)
        "const erx_profile_t #{prefix}_profile = {\n" \
          "\t.kinds = kinds, .names = names, .refers = #{refers}, .totals = #{totals},\n" \
          "\t.tables = #{tables}, .frames = frames, .version = #{@protocol.fetch(:version)},\n" \
          "\t.frame_max = #{@protocol.dig(:frame_max, :value)}, .nkinds = #{@order.size}, .nnames = #{@names.size},\n" \
          "\t.nrefers = #{nrefers}, .ntotals = #{ntotals}, .ntables = #{ntables},\n" \
          "\t.nframes = #{@protocol.fetch(:frames).size}, .slot_kind = #{@order.index('slot') || 'ERX_PROFILE_NONE'},\n" \
          "\t.unique_kind = #{unique}, .depth = #{@protocol.fetch(:depth)},\n};\n"
      end

      # Static asserts that the C check's fixed bounds (erx/profile.h) hold
      # this table: the model's depth and totals bounds are the header's, the
      # table's depth and totals are within them, each map's keys and each
      # union's cases fit a level's mask, and each list's iterator is its view
      # alone, which the check stores at the iterator's offset.
      def bounds
        model = Protocols::Profile
        masks = @kinds.filter_map do |name, kind|
          case kind.fetch(:form)
          when 'map' then "#{name}_fields"
          when 'union' then "#{name}_cases" unless kind.fetch(:cases).empty?
          end
        end
        lists = @kinds.select { |_, kind| kind.fetch(:form) == 'list' }.keys
        [assertion("ERX_PROFILE_DEPTH_MAX == #{model::DEPTH_MAX}", 'the generator bounds depth as erx/profile.h does'),
         assertion("ERX_PROFILE_SLOTS == #{model::SLOTS}", 'the generator counts slots as erx/profile.h does'),
         assertion("ERX_PROFILE_TOTALS_MAX == #{model::TOTALS_MAX}", 'the generator bounds totals as erx/profile.h does'),
         assertion("#{@protocol.fetch(:depth)} <= ERX_PROFILE_DEPTH_MAX", "#{short}'s kinds nest within the check's stack"),
         *(@protocol.fetch(:totals).empty? ? [] : [assertion('NELEM(totals) <= ERX_PROFILE_TOTALS_MAX', "#{short}'s totals fit the check's sums")]),
         *masks.map { |table| assertion("NELEM(#{table}) <= ERX_PROFILE_KEYS_MAX", "#{table} fit a level's mask") },
         *lists.map do |name|
           type = c_type(name)
           assertion("offsetof(#{type}, view) == 0 &&\n    sizeof(#{type}) == sizeof(erx_profile_list_t)",
                     "#{type} is its view alone")
         end, ''].join("\n")
      end

      # Each union a frame carries whose cases hold capabilities, with each case
      # and the C members of its capabilities, from the positions the profile's
      # validation found (Protocols::Profile.capability_fields).
      def capability_walks
        @protocol.fetch(:capabilities).map do |name, positions|
          cases = @kinds.fetch(name).fetch(:cases).map do |item|
            members = member_names(item.fetch(:fields))
            [item, positions.fetch(item.fetch(:c_name)).map { |at| members.fetch(at) }]
          end
          [name, cases]
        end
      end

      def caps_max(name) = "#{prefix}_#{name}_caps".upcase

      def cap_prototypes
        capability_walks.map do |name, cases|
          most = cases.map { |_, members| members.size }.max
          "\n/* The most capabilities one #{name} holds, over its cases. */\n" \
            "#define\t#{caps_max(name)}\t#{most}\n" \
            "/* Names the capabilities #{name} holds, into caps[0, n), in its case's order; returns n. */\n" \
            "size_t\t#{prefix}_#{name}_caps(const #{c_type(name)} *#{name},\n\t    erx_cap_t caps[#{caps_max(name)}]);"
        end.join("\n")
      end

      def cap_functions
        capability_walks.map do |name, cases|
          holding, none = cases.partition { |_, members| members.any? }
          arms = holding.map do |item, members|
            stores = members.each_with_index.map { |member, at| "\t\tcaps[#{at}] = #{name}->u.#{item.fetch(:c_name)}.#{member};" }
            "\tcase #{enum_name(name, item.fetch(:atoms))}:\n#{stores.join("\n")}\n\t\treturn (#{members.size});"
          end
          empty = none.map { |item, _| "\tcase #{enum_name(name, item.fetch(:atoms))}:" }
          arms << "#{empty.join("\n")}\n\t\treturn (0);" unless empty.empty?
          "size_t\n#{prefix}_#{name}_caps(const #{c_type(name)} *#{name}, erx_cap_t caps[#{caps_max(name)}])\n{\n" \
            "\tswitch (#{name}->which) {\n#{arms.join("\n")}\n\t}\n\treturn (0);\n}\n"
        end.join("\n")
      end

      def assertion(condition, message) = "_Static_assert(#{condition},\n    \"#{message}\");"

      # P_check_to_program: the frame the envelope selects (erx_profile_select),
      # then that frame's own check into its member of the struct.
      def to_program_function
        return '' if to_program.empty?

        arms = to_program.map do |frame|
          name = frame.fetch(:name)
          arguments = [*(reply?(frame) ? ['busy'] : []), *(frame.fetch(:slot) ? ['&to_program->slot'] : []),
                       "&to_program->u.#{name}"].join(', ')
          "\tcase #{frame_constant(frame)}:\n\t\treturn (#{prefix}_check_#{name}(frame, len, scratch, scratch_len,\n" \
            "\t\t    #{arguments}, refusal));"
        end
        "bool\n#{prefix}_check_to_program(const uint8_t *frame, size_t len, void *scratch,\n" \
          "    size_t scratch_len, const uint16_t busy[ERX_PROFILE_SLOTS],\n" \
          "    #{prefix}_to_program_t *to_program, erx_profile_refusal_t *refusal)\n{\n" \
          "\tstatic const uint16_t to_frames[] = { #{to_program.map { |frame| frame_constant(frame) }.join(', ')} };\n\n" \
          "\tto_program->frame = erx_profile_select(&#{prefix}_profile, to_frames,\n\t    NELEM(to_frames), frame, len);\n" \
          "\tto_program->slot = 0;\n" \
          "\tswitch (to_program->frame) {\n#{arms.join("\n")}\n\t}\n" \
          "\t/* erx_profile_select answers one of to_frames. */\n\t*refusal = (erx_profile_refusal_t){ .reason = ERX_PROFILE_SHAPE,\n" \
          "\t    .kind = ERX_PROFILE_NONE };\n\treturn (false);\n}\n"
      end

      # Each frame's check over erx_profile_check. A reply frame's value is
      # the reply struct's union, and the request case its slot holds is
      # named once the check accepts it.
      def functions
        frames = @frames.map do |frame|
          name = frame.fetch(:name)
          call = "erx_profile_check(&#{prefix}_profile, #{frame_constant(frame)}, frame, len, scratch,\n" \
                 "\t    scratch_len, #{reply?(frame) ? 'busy' : 'NULL'}, #{frame.fetch(:slot) ? 'slot' : 'NULL'}, " \
                 "#{reply?(frame) ? "&#{name}->u" : name}, refusal)"
          body = if reply?(frame)
                   "\tif (!#{call})\n\t\treturn (false);\n\t#{name}->request = busy[*slot];\n\treturn (true);\n"
                 else
                   "\treturn (#{call});\n"
                 end
          "bool\n#{prefix}_check_#{name}(const uint8_t *frame, size_t len, void *scratch,\n" \
            "    size_t scratch_len, #{check_parameters(frame)}, erx_profile_refusal_t *refusal)\n{\n#{body}}\n"
        end
        lists = @kinds.select { |_, kind| kind.fetch(:form) == 'list' }.map do |name, kind|
          "bool\n#{prefix}_#{name}_next(#{c_type(name)} *it, #{c_type(kind.fetch(:element))} *element)\n{\n" \
            "\treturn (erx_profile_next(&#{prefix}_profile, #{index(name)}, &it->view, element));\n}\n"
        end
        ["size_t\n#{prefix}_scratch_bytes(size_t len)\n{\n\treturn (erx_profile_scratch_bytes(&#{prefix}_profile, len));\n}\n",
         *frames, *lists,
         "const char *\n#{prefix}_kind_name(uint16_t kind)\n{\n\treturn (erx_profile_name(&#{prefix}_profile, kind));\n}\n"].join("\n")
      end
    end
  end
